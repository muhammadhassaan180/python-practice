first_name = "Muhammad"
last_name = "Hassaan"

# 1. Concatenation: join the two names with a space between them
full_name = first_name + " " + last_name
print(full_name)

# 2. String interpolation: do the same with an f-string
full_name_f = f"{first_name} {last_name}"
print(full_name_f)

